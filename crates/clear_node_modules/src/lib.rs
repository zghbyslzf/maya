use maya_common::error::Result;
use maya_common::file_utils::find_directories_by_name_pruned;
use maya_common::RemovalReport;
use std::fs;
use std::path::Path;

/// 清除 node_modules 目录
pub fn clear_node_modules<P: AsRef<Path>>(dir: P) -> Result<RemovalReport> {
    let dir = dir.as_ref();

    // 命中 node_modules 后停止进入该目录，避免父目录删除后再次删除嵌套目标。
    let node_modules_dirs = find_directories_by_name_pruned(dir, "node_modules")?;

    let mut report = RemovalReport::default();
    for dir_path in node_modules_dirs {
        // 删除目录及其所有内容
        match fs::remove_dir_all(&dir_path) {
            Ok(()) => {
                report.removed.push(dir_path);
            }
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                report.skipped.push(dir_path);
            }
            Err(error) => {
                return Err(maya_common::Error::io_context(
                    "删除 node_modules 目录",
                    dir_path,
                    error,
                ));
            }
        }
    }

    Ok(report)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs::{create_dir, create_dir_all, File};
    use tempfile::tempdir;

    #[test]
    fn test_clear_node_modules() {
        let temp_dir = tempdir().unwrap();
        let node_modules_path = temp_dir.path().join("node_modules");
        create_dir(&node_modules_path).unwrap();
        let file_path = node_modules_path.join("test.js");
        File::create(&file_path).unwrap();
        assert!(node_modules_path.exists());
        let report = clear_node_modules(temp_dir.path()).unwrap();
        assert_eq!(report.removed_count(), 1);
        assert!(!node_modules_path.exists());
    }

    #[test]
    fn test_clear_nested_node_modules() {
        let temp_dir = tempdir().unwrap();
        let outer = temp_dir.path().join("node_modules");
        let nested = outer.join("dependency").join("node_modules");
        create_dir_all(&nested).unwrap();
        File::create(nested.join("nested.js")).unwrap();

        let report = clear_node_modules(temp_dir.path()).unwrap();

        assert_eq!(report.removed_count(), 1);
        assert!(!outer.exists());
    }

    #[test]
    fn test_clear_multiple_sibling_node_modules() {
        let temp_dir = tempdir().unwrap();
        let first = temp_dir.path().join("app").join("node_modules");
        let second = temp_dir
            .path()
            .join("packages")
            .join("lib")
            .join("node_modules");
        create_dir_all(&first).unwrap();
        create_dir_all(&second).unwrap();

        let report = clear_node_modules(temp_dir.path()).unwrap();

        assert_eq!(report.removed_count(), 2);
        assert!(!first.exists());
        assert!(!second.exists());
    }

    #[test]
    fn test_disappeared_target_is_not_reported_as_deleted() {
        let temp_dir = tempdir().unwrap();
        let target = temp_dir.path().join("node_modules");
        create_dir(&target).unwrap();

        let targets = find_directories_by_name_pruned(temp_dir.path(), "node_modules").unwrap();
        fs::remove_dir_all(&target).unwrap();

        let mut count = 0;
        for target in targets {
            match fs::remove_dir_all(target) {
                Ok(()) => count += 1,
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
                Err(error) => panic!("意外删除错误: {error}"),
            }
        }

        assert_eq!(count, 0);
    }
}
